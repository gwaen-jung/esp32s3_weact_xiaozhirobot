#!/usr/bin/env python3
"""Generate font_8x16.h (ASCII + Vietnamese) from DejaVu Sans Mono.

DejaVu fonts are derived from Bitstream Vera (permissive license); the rendered
bitmaps are embedded only as a tiny subtitle font.
Usage: python3 gen_font_8x16.py [path/to/DejaVuSansMono.ttf] > ../font_8x16.h
"""
import sys
import unicodedata
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
W, H, SIZE, BASELINE = 8, 16, 12, 12

chars = set(chr(c) for c in range(0x20, 0x7F))
vowels = "aăâeêioôơuưyAĂÂEÊIOÔƠUƯY"
tones = ["", "̀", "́", "̃", "̉", "̣"]
for v in vowels:
    for t in tones:
        chars.add(unicodedata.normalize("NFC", v + t))
chars |= set("đĐ")
chars = sorted(c for c in chars if len(c) == 1)

font = ImageFont.truetype(TTF, SIZE)
out = []
for ch in chars:
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.text((0, BASELINE), ch, font=font, fill=255, anchor="ls")
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)) >= 110:
                b |= 0x80 >> x
        rows.append(b)
    out.append((ord(ch), rows, ch))

print("// Generated by tools/gen_font_8x16.py - do not edit.")
print("// 8x16 bitmap glyphs (MSB = left pixel), ASCII + Vietnamese, from DejaVu Sans Mono.")
print("#pragma once\n#include <cstdint>\n")
print("static const uint32_t kFont8x16Codepoints[%d] = {" % len(out))
print("    " + ", ".join("0x%04X" % cp for cp, _, _ in out))
print("};\n")
print("static const uint8_t kFont8x16Bitmaps[%d][16] = {" % len(out))
for cp, rows, ch in out:
    label = ch if ch not in "\\" else "backslash"
    print("    {%s},  // U+%04X %s" % (", ".join("0x%02X" % r for r in rows), cp, label))
print("};")
